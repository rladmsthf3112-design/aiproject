# 지도 생성
m = folium.Map(
    location=[37.5665, 126.9780],
    zoom_start=11,
    tiles="OpenStreetMap"
)

# 관광지 마커 추가
for spot in spots:
    folium.Marker(
        [spot["lat"], spot["lon"]],
        popup=f"""
        <b>{spot['name']}</b><br>
        가까운 역: {spot['station']}
        """,
        tooltip=spot["name"],
        icon=folium.Icon(color="red", icon="info-sign")
    ).add_to(m)

# 지도 출력 (크기 60% 정도로 축소)
st_folium(m, width=700, height=450)

st.divider()

# 관광지 선택
selected = st.selectbox(
    "📍 관광지를 선택하세요",
    [spot["name"] for spot in spots]
)

# 선택된 관광지 정보 출력
for spot in spots:
    if spot["name"] == selected:
        st.subheader(f"🏙️ {spot['name']}")
        st.write(f"🚇 가장 가까운 지하철역: {spot['station']}")
        st.markdown("### 🎉 즐길거리")
        st.write(spot["fun"])
        break
